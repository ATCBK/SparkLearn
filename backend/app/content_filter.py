# ──────────────────────────────────────────────
# 构建匹配器
# ──────────────────────────────────────────────

# 精确短语匹配（长词，直接搜索）
_ALL_PHRASES = _POLITICAL_PHRASES + _PORNOGRAPHIC + _VIOLENT + _DISCRIMINATORY
_PHRASE_PATTERN = re.compile(
    "|".join(re.escape(w) for w in _ALL_PHRASES),
    re.IGNORECASE,
)

# 子串匹配（短关键词，用于严格过滤）
_SUBSTR_PATTERN = re.compile(
    "|".join(re.escape(w) for w in _POLITICAL_SUBSTRINGS),
    re.IGNORECASE,
)


def _strip_html(text: str) -> str:
    """移除 HTML 标签"""
    return re.sub(r"<[^>]+>", "", text)


def check_keyword(keyword: str) -> tuple[bool, str]:
    """检查搜索关键词是否包含敏感词

    Returns:
        (is_blocked, reason): is_blocked=True 表示被拦截
    """
    if _PHRASE_PATTERN.search(keyword) or _SUBSTR_PATTERN.search(keyword):
        return True, "搜索内容包含不当关键词，请修改后重试"
    return False, ""


def filter_results(items: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """严格过滤搜索结果中的敏感内容

    检查每条结果的全部字段（title、summary、author、url、tags、extra_data）。
    标题和摘要使用子串匹配（最严格），其他字段使用短语匹配。
    只要任何字段命中敏感词，整条结果（含图片）都会被移除。
    """
    filtered = []
    for item in items:
        # 收集所有文本字段
        title = _strip_html(str(item.get("title", "")))
        summary = _strip_html(str(item.get("summary", "")))
        author = str(item.get("author", ""))
        url = str(item.get("url", ""))
        tags = " ".join(str(t) for t in item.get("tags", []))

        # extra_data 也可能包含敏感信息
        extra = item.get("extra_data", {})
        extra_text = ""
        if isinstance(extra, dict):
            extra_text = " ".join(str(v) for v in extra.values())

        # 标题和摘要使用子串匹配（最严格）
        # 标题是内容的最直接描述，必须严格过滤
        if _SUBSTR_PATTERN.search(title):
            continue
        if _SUBSTR_PATTERN.search(summary):
            continue

        # 全字段使用短语匹配
        combined = " ".join([title, summary, author, url, tags, extra_text])
        if _PHRASE_PATTERN.search(combined):
            continue

        filtered.append(item)
    return filtered
